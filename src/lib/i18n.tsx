interface Ctx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: keyof typeof en) => string;
  city: CityId;
  setCity: (c: CityId) => void;
  cityName: (c: CityId) => string;
}
const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  const [city, setCityState] = useState<CityId>("hyderabad");
  useEffect(() => {
    if (typeof window === "undefined") return;
    const savedLang = localStorage.getItem("smartflow_lang");
    const savedCity = localStorage.getItem("smartflow_city");
    if (savedLang) setLangState(savedLang as Lang);
    if (savedCity) setCityState(savedCity as CityId);
  }, []);
  const setLang = (l: Lang) => {
    setLangState(l);
    if (typeof window !== "undefined") localStorage.setItem("smartflow_lang", l);
  };
  const setCity = (c: CityId) => {
    setCityState(c);
    if (typeof window !== "undefined") localStorage.setItem("smartflow_city", c);
  };
  const t = (k: keyof typeof en) => {
    const d = dicts[lang] || {};
    return (d[k] as string) || en[k] || (k as string);
  };
  const cityName = (c: CityId) => t(`city_${c}` as keyof typeof en);
  const isRtl = lang === "ur";
  useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = lang;
      document.documentElement.dir = isRtl ? "rtl" : "ltr";
    }
  }, [lang, isRtl]);
  return (
    <I18nContext.Provider value={{ lang, setLang, t, city, setCity, cityName }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const c = useContext(I18nContext);
  if (!c) throw new Error("useI18n must be inside I18nProvider");
  return c;
}
