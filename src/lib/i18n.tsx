interface Ctx { lang: Lang; setLang: (l: Lang) => void; t: (k: keyof typeof en) => string; }
const I18nContext = createContext<Ctx | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    const saved = typeof window !== "undefined" ? localStorage.getItem("smartflow_lang") : null;
    if (saved) setLangState(saved as Lang);
  }, []);
  const setLang = (l: Lang) => {
    setLangState(l);
    if (typeof window !== "undefined") localStorage.setItem("smartflow_lang", l);
  };
  const t = (k: keyof typeof en) => {
    const d = dicts[lang] || {};
    return (d[k] as string) || en[k] || (k as string);
  };
  const isRtl = lang === "ur";
  useEffect(() => {
    if (typeof document !== "undefined") {
      document.documentElement.lang = lang;
      document.documentElement.dir = isRtl ? "rtl" : "ltr";
    }
  }, [lang, isRtl]);
  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const c = useContext(I18nContext);
  if (!c) throw new Error("useI18n must be inside I18nProvider");
  return c;
}
